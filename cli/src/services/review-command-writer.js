function readTemplate() {
  return fs.readFileSync(path.join(CLI_ROOT, REVIEW_COMMAND_TEMPLATE), 'utf-8');
}

function buildReviewCommand(toolKey) {
  const definition = REVIEW_COMMAND_DEFINITIONS[toolKey];
  if (!definition) {
    throw new Error(`No architecture review command definition for tool: ${toolKey}`);
  }

  const body = readTemplate()
    .replace('{{RULES_INSTRUCTION}}', definition.rulesInstruction)
    .replace('{{SCOPE_INSTRUCTION}}', definition.scopeInstruction)
    .trim();

  const parts = [];
  if (definition.frontmatter) {
    parts.push('---', ...definition.frontmatter, '---', '');
  }
  parts.push(
    '# Tenets Architecture Review',
    '',
    '> Auto-generated by tenets. Run `npx tenets update` to update.',
    '',
    body,
    ''
  );
  return parts.join('\n');
}

function writeReviewCommand(projectRoot, toolKey) {
  const definition = REVIEW_COMMAND_DEFINITIONS[toolKey];
  if (!definition) return null;

  const targetPath = path.join(projectRoot, definition.targetFile);
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, buildReviewCommand(toolKey), 'utf-8');
  return definition.targetFile;
}

function reviewCommandExists(projectRoot, toolKey) {
  const definition = REVIEW_COMMAND_DEFINITIONS[toolKey];
  return Boolean(
    definition && fs.existsSync(path.join(projectRoot, definition.targetFile))
  );
}

module.exports = {
  REVIEW_COMMAND_DEFINITIONS,
  buildReviewCommand,
  writeReviewCommand,
  reviewCommandExists,
};
