const fs = require('node:fs');
const path = require('node:path');
const { GENERATED_MARKER } = require('../constants');
const {
  isTenetsOwnedFile,
  writeOwnedFile,
} = require('./file-writer');

const CLI_ROOT = path.join(__dirname, '..', '..');
const SCAFFOLD_COMMAND_TEMPLATE = 'templates/commands/tenets-scaffold.md';

const SCAFFOLD_COMMAND_DEFINITIONS = {
  claude: {
    targetFile: '.claude/skills/tenets-scaffold/TENETS-SKILL.md',
    frontmatter: [
      'name: tenets-scaffold',
      'description: Initialize a Flask service with Tenets architecture guardrails.',
      'allowed-tools: Read Grep Glob Write Edit Bash',
    ],
    rulesInstruction:
      'Read every rule file matching `.claude/rules/tenets-*.md` before planning.',
  },
  augment: {
    targetFile: '.augment/commands/tenets-scaffold.md',
    frontmatter: [
      'description: Initialize a Flask service with Tenets architecture guardrails',
    ],
    rulesInstruction:
      'Read every rule file matching `.augment/rules/tenets-*.md` before planning.',
  },
  cursor: {
    targetFile: '.cursor/commands/tenets-scaffold.md',
    rulesInstruction:
      'Read every rule file matching `.cursor/rules/tenets-*.mdc` before planning.',
  },
  copilot: {
    targetFile: '.github/prompts/tenets-scaffold.prompt.md',
    frontmatter: [
      'description: Initialize a Flask service with Tenets architecture guardrails',
      'agent: agent',
    ],
    rulesInstruction:
      'Read `.github/copilot-instructions.md` and every `.github/instructions/tenets-*.instructions.md` file before planning.',
  },
  agents: {
    targetFile: '.tenets/prompts/tenets-scaffold.md',
    rulesInstruction:
      'Read `AGENTS.md` in full before planning, including every rule inside the Tenets markers.',
  },
};

function readTemplate() {
  return fs.readFileSync(
    path.join(CLI_ROOT, SCAFFOLD_COMMAND_TEMPLATE),
    'utf-8'
  );
}

function buildScaffoldCommand(toolKey) {
  const definition = SCAFFOLD_COMMAND_DEFINITIONS[toolKey];
  if (!definition) {
    throw new Error(`No scaffold command definition for tool: ${toolKey}`);
  }

  const body = readTemplate()
    .replace('{{RULES_INSTRUCTION}}', definition.rulesInstruction)
    .trim();
  const parts = [];
  if (definition.frontmatter) {
    parts.push('---', ...definition.frontmatter, '---', '');
  }
  parts.push(
    GENERATED_MARKER,
    '',
    '# Tenets Service Scaffold',
    '',
    '> Auto-generated by tenets. Run `npx tenets update` to update.',
    '',
    body,
    ''
  );
  return parts.join('\n');
}

function scaffoldCommandPath(projectRoot, toolKey) {
  const definition = SCAFFOLD_COMMAND_DEFINITIONS[toolKey];
  if (!definition) return null;
  return path.join(projectRoot, definition.targetFile);
}

function writeScaffoldCommand(projectRoot, toolKey, options = {}) {
  const definition = SCAFFOLD_COMMAND_DEFINITIONS[toolKey];
  if (!definition) return null;

  const targetPath = scaffoldCommandPath(projectRoot, toolKey);
  writeOwnedFile(
    targetPath,
    buildScaffoldCommand(toolKey),
    options
  );
  return definition.targetFile;
}

function scaffoldCommandExists(projectRoot, toolKey) {
  const targetPath = scaffoldCommandPath(projectRoot, toolKey);
  return Boolean(targetPath && isTenetsOwnedFile(targetPath));
}

module.exports = {
  SCAFFOLD_COMMAND_DEFINITIONS,
  buildScaffoldCommand,
  scaffoldCommandPath,
  writeScaffoldCommand,
  scaffoldCommandExists,
};
